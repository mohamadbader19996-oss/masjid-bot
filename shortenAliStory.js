require('dotenv').config();
const { askGemini } = require('./src/services/gemini');

const LONG =
  'وقف كاسيوس كلاي في قمة مجده أمام خيار لم يتوقعه أحد: الحرب تطلبه، والعالم يهتف باسمه، لكن قلبه قال لا. قالها بصوتٍ لم يخشَ الجماهير: «لا عداء لي مع الفيتناميين، لن أقتل إنساناً لم يؤذني». كان ذلك الرفض الصريح لشرف الخدمة العسكرية في حرب فيتنام ضربة قاصمة لمسيرته الرياضية؛ فقد خسر لقبه العالمي، خسر أموالاً طائلة، وخسر جزءاً كبيراً من مجده الذي بناه بشق الأنفس، لكنه في المقابل لم يخسر ضميره أو كرامته. في تلك اللحظة المصيرية، لم تكن حلبة الملاكمة هي ساحة البطولة الحقيقية، بل البطولة كانت في الوقوف بشجاعة مع المبادئ والقناعات الخاصة، ولو كان ذلك يعني مواجهة العالم بأكمله وحيداً. وجد في اعتناقه للإسلام ما لم تمنحه له كل الجوائز والميداليات: إخاءً سامياً يتجاوز كل الحدود، وكرامةً أصيلة لا يمكن شراؤها بذهب العالم، ومعنىً عميقاً للحرية يفوق بكثير كل حزام بطولة. وحين غير اسمه إلى محمد علي، لم يكن ذلك مجرد تغيير شكلي للاسم، بل كان إيذاناً بولادة روح جديدة، روح رفضت أن تُقاس أو تُقَيَّم بانتصارات جسدية مؤقتة، بل صارت بطلاً حقيقياً في ساحة الضمير الإنساني، يدافع عن حقوق الإنسان وقيمه قبل أن يدافع عن أي لقب أو مجد دنيوي. لقد أثبت أن أعظم الانتصارات هي تلك التي نحققها داخل أنفسنا، وأن الشجاعة الحقيقية تكمن في الصدق مع الذات والتمسك بالمبادئ.';

const SYSTEM = 'محرر عربي. أرجع JSON فقط: {"story":"..."}. 175-185 كلمة. فقرة واحدة.';

async function main() {
  const { text, model } = await askGemini(
    'اختصر هذه القصة إلى 180 كلمة بالضبط مع الإبقاء على: رفض الحرب، "لا عداء لي مع الفيتناميين"، خسارة اللقب، الكرامة في الإسلام بعيداً عن الحلبة، محمد علي، جملة ختامية ملهمة.\n\n' + LONG,
    SYSTEM
  );
  let raw = text.trim();
  const fence = raw.match(/```(?:json)?\s*([\s\S]*?)```/i);
  if (fence) raw = fence[1].trim();
  const { story } = JSON.parse(raw.slice(raw.indexOf('{'), raw.lastIndexOf('}') + 1));
  const clean = story.replace(/\n+/g, ' ').trim();
  console.log(`${model} | ${clean.split(/\s+/).filter(Boolean).length} كلمة\n`);
  console.log(clean);
}

main().catch((e) => { console.error(e.message); process.exit(1); });
