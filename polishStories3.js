function parse(text) {
  let raw = text.trim();
  const f = raw.match(/```[\s\S]*?```/);
  if (f) raw = f[0].replace(/```json?/i, '').replace(/```/g, '').trim();
  return JSON.parse(raw.slice(raw.indexOf('{'), raw.lastIndexOf('}') + 1)).story.replace(/\n+/g, ' ').trim();
}

function wc(t) {
  return t.split(/\s+/).filter(Boolean).length;
}

